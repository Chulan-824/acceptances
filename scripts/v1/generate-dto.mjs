import { readFileSync, writeFileSync } from "node:fs";
const names = [
  "common",
  "definitions",
  "target",
  "plan",
  "report",
  "manifest",
  "evaluation",
  "snapshot",
];
const schemas = Object.fromEntries(
  names.map((name) => [
    name,
    JSON.parse(readFileSync(`contracts/schemas/${name}.json`, "utf8")),
  ]),
);
const declarations = new Map();
const upper = (name) =>
  name.replace(/(^|[^a-zA-Z0-9])([a-zA-Z0-9])/g, (_, prefix, char) =>
    char.toUpperCase(),
  );
function refType(ref) {
  const [file, path = ""] = ref.split("#");
  const key = file
    ? file
        .split("/")
        .at(-1)
        .replace(/\.json$/, "")
    : "common";
  let schema = schemas[key];
  for (const part of path.split("/").filter(Boolean)) schema = schema[part];
  const name = upper(key === "common" ? path.split("/").at(-1) : key) + "DTO";
  return type(schema, name);
}
function type(schema, name) {
  if (schema.$ref) return refType(schema.$ref);
  const alternatives = schema.anyOf || schema.oneOf;
  if (alternatives) {
    const nonNull = alternatives.filter((item) => item.type !== "null");
    if (nonNull.length === 1 && nonNull.length < alternatives.length)
      return "*" + type(nonNull[0], name);
    return "json.RawMessage";
  }
  let kind = schema.type;
  if (!kind && typeof schema.const === "string") kind = "string";
  if (!kind && schema.enum?.every((value) => typeof value === "string"))
    kind = "string";
  if (Array.isArray(kind)) {
    const nonNull = kind.filter((k) => k !== "null");
    if (nonNull.length === 1 && nonNull.length < kind.length)
      return "*" + type({ ...schema, type: nonNull[0] }, name);
    return "json.RawMessage";
  }
  if (kind === "array") return "[]" + type(schema.items || {}, name + "Item");
  if (kind === "object") {
    if (!schema.properties)
      return (
        "map[string]" +
        type(
          typeof schema.additionalProperties === "object"
            ? schema.additionalProperties
            : {},
          name + "Value",
        )
      );
    if (declarations.has(name)) return name;
    declarations.set(name, "");
    const required = new Set(schema.required || []);
    const fields = Object.entries(schema.properties).map(([key, value]) => {
      let fieldType = type(value, name + upper(key));
      const optional = !required.has(key);
      if (
        optional &&
        !fieldType.startsWith("*") &&
        !fieldType.startsWith("[]") &&
        !fieldType.startsWith("map[") &&
        fieldType !== "json.RawMessage"
      )
        fieldType = "*" + fieldType;
      const field = upper(key)
        .replace(/Id$/, "ID")
        .replace(/Ids$/, "IDs")
        .replace(/Sha256$/, "SHA256");
      return ` ${field} ${fieldType} \`json:"${key}${optional ? ",omitempty" : ""}"\``;
    });
    declarations.set(name, `type ${name} struct {\n${fields.join("\n")}\n}`);
    return name;
  }
  if (kind === "string") return "string";
  if (kind === "integer") return "JSONInteger";
  if (kind === "number") return "float64";
  if (kind === "boolean") return "bool";
  return "json.RawMessage";
}
for (const name of names.slice(1)) type(schemas[name], upper(name) + "DTO");
const decoder = names
  .slice(1)
  .map((name) => ` case "${name}": value=&${upper(name)}DTO{}`)
  .join("\n");
writeFileSync(
  "internal/protocol/dto.generated.go",
  `// Code generated by scripts/v1/generate-dto.mjs from contracts/schemas. DO NOT EDIT.\npackage protocol\nimport("encoding/json";"bytes";"fmt")\n\n${[...declarations.values()].join("\n\n")}\n\nfunc decodeDTO(kind string,raw []byte)(any,error){\n var value any\n switch kind{\n${decoder}\n default:return nil,fmt.Errorf("unknown DTO kind")}\n decoder:=json.NewDecoder(bytes.NewReader(raw));decoder.DisallowUnknownFields()\n if err:=decoder.Decode(value);err!=nil{return nil,err};return value,nil\n}\n`,
);
